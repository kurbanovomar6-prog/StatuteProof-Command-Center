# ── Алгоритм взвешенного семантического скоринга ──────────────────────────────

def _frequency_density_score(
    text_lower: str,
    weights: dict[str, int],
    extra_keywords: list[str] | None = None,
) -> tuple[float, list[str]]:
    """
    Взвешенный скоринг с учётом частотной плотности термина в документе.

    Частотный множитель (логарифмический):
      1 вхождение  → ×1.0 (базовый вес)
      2-3 вхождения → ×1.5 (термин употреблён несколько раз — характерно для НПА)
      4+ вхождений  → ×2.0 (термин системообразующий для документа)

    Возвращает (суммарный_скор, список_совпавших_терминов_с_деталями).
    """
    # Расширяем словарь кастомными ключевыми словами регулятора (вес 2)
    combined = dict(weights)
    if extra_keywords:
        for kw in extra_keywords:
            k = kw.lower().strip()
            if k and k not in combined:
                combined[k] = 2

    score:   float     = 0.0
    matched: list[str] = []

    for term, weight in combined.items():
        count = text_lower.count(term)
        if count == 0:
            continue

        # Логарифмический множитель частоты
        if count == 1:
            freq_mult = 1.0
        elif count <= 3:
            freq_mult = 1.5
        else:
            freq_mult = 2.0

        contribution = weight * freq_mult
        score += contribution
        matched.append(f"{term}(+{weight}×{freq_mult:.1f}×{count})")

    return score, matched


# ── Публичный API ──────────────────────────────────────────────────────────────

def is_regulatory(
    text: str,
    jurisdiction: str = "DEFAULT",
    extra_keywords: list[str] | None = None,
) -> tuple[bool, str]:
    """
    Двухэтапная проверка релевантности текста документа.

    Этап 1: быстрое отсечение очевидного шума по ключевым фразам.
    Этап 2: взвешенный семантический скоринг против порога юрисдикции.
    Этап 2b: если юрисдикция нераспознана — fallback на DEFAULT/EN словарь.

    Возвращает (ok: bool, reason: str).
    Вызывать ДО extract_regulation() — экономит GPT-токены.

    Документы ниже порога молча архивируются (статус 'ARCHIVED' / пропуск).
    """
    # ── Ограничения длины ─────────────────────────────────────────────────────
    if len(text) < _MIN_CHARS:
        return False, f"too_short:{len(text)}<{_MIN_CHARS}"

    if len(text) > _MAX_CHARS:
        return False, f"too_long:{len(text)}>{_MAX_CHARS}"

    text_lower = text.lower()

    # ── Этап 1: Быстрое отсечение шума по фразам ──────────────────────────────
    for noise in _NOISE_TEXTS:
        if noise in text_lower:
            return False, f"noise_phrase:'{noise[:50]}'"

    # ── Этап 2: Взвешенный семантический скоринг ──────────────────────────────
    jur_key  = jurisdiction.upper().strip()
    weights  = _JURISDICTION_WEIGHTS.get(jur_key, _JURISDICTION_WEIGHTS["DEFAULT"])
    threshold = _SCORE_THRESHOLDS.get(jur_key, _SCORE_THRESHOLD_DEFAULT)

    score, matched = _frequency_density_score(text_lower, weights, extra_keywords)

    if score >= threshold:
        return True, (
            f"ok:score={score:.1f}≥{threshold}:"
            f"matched=[{', '.join(matched[:4])}]"
        )

    # ── Этап 2b: Fallback на DEFAULT-словарь если юрисдикция нераспознана ─────
    if jur_key not in _JURISDICTION_WEIGHTS:
        default_weights = _JURISDICTION_WEIGHTS["DEFAULT"]
        default_score, default_matched = _frequency_density_score(
            text_lower, default_weights
        )
        default_threshold = _SCORE_THRESHOLDS.get("EN", _SCORE_THRESHOLD_DEFAULT)
        if default_score >= default_threshold:
            return True, (
                f"ok:default_score={default_score:.1f}≥{default_threshold}:"
                f"matched=[{', '.join(default_matched[:3])}]"
            )

    # Документ не прошёл порог — архивируется без GPT-вызова
    log.debug(
        "prefilter: отклонён (score=%.1f < threshold=%d) | первые совпадения: %s",
        score, threshold, matched[:3] if matched else "нет совпадений",
    )
    return False, f"low_score:{score:.1f}<{threshold}"


def is_regulatory_url(url: str) -> tuple[bool, str]:
    """
    Быстрая URL-проверка до скачивания файла.
    Фильтрует пресс-релизы, курсы валют и нерелевантные пути.
    Возвращает (ok: bool, reason: str).
    """
    url_lower = url.lower()

    # Шумовые URL-паттерны — нормативный акт такой структуры иметь не может
    for pat in _NOISE_URL_PATTERNS:
        if pat.search(url_lower):
            return False, f"noise_url:{pat.pattern}"

    # Документные расширения или пути — хотя бы одно должно присутствовать
    has_doc_ext  = any(url_lower.endswith(ext) for ext in _DOC_EXTENSIONS)
    has_doc_path = any(p in url_lower for p in _DOC_URL_PATHS)

    if not (has_doc_ext or has_doc_path):
        return False, "not_document_url"

    return True, "ok"
